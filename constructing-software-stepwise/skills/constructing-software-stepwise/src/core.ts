export const indentOf = (line: string): number => line.length - lstrip(line).length
const count = (s: string, ch: string): number => s.split(ch).length - 1

export const joinContinuations = (raw: string[]): string[] => {
  const out: string[] = []
  let buf = ""
  let depth = 0
  for (const ln of raw) {
    if (depth <= 0 && out.length && strip(ln) && continues(out[out.length - 1], ln)) {
      out[out.length - 1] = merge(out[out.length - 1], ln)
      continue
    }
    buf = depth <= 0 ? ln : rstrip(buf) + (strip(ln).startsWith(")") || rstrip(buf).endsWith("(") ? "" : " ") + strip(ln)
    depth += count(ln, "(") - count(ln, ")")
    if (depth <= 0) {
      out.push(buf)
      buf = ""
      depth = 0
    }
  }
  if (buf) out.push(buf)
  return out
}

/** A deeper-indented line under an untagged, non-block statement wraps it (multi-line SQL, long expressions). */
export const continues = (prev: string, ln: string): boolean => {
  const [code, comment] = splitComment(prev)
  return Boolean(strip(code)) && !comment && stmtKind(code) === "stmt" && !rstrip(code).endsWith(":") && indentOf(ln) > indentOf(prev)
}

export const merge = (prev: string, ln: string): string => {
  const [code, sep, tag] = splitComment(ln)
  const joined = rstrip(prev) + " " + strip(code)
  return sep ? `${joined} --${tag}` : joined
}

export class BodyError extends Error {}

export const parseBody = (text: string, fn: string): BodyItem[] => {
  let raw = text.split(/\r\n|[\n\r\v\f\x1c\x1d\x1e\x85\u2028\u2029]/u).filter((ln) => strip(ln))
  if (raw.length) {
    const first = strip(raw[0])
    const prefix = split(first, " ", 1)[0].toLowerCase()
    if (prefix === "procedure" || prefix === "function") {
      if (fnOf(first) !== fn) throw new BodyError(`procedure signature must match ${fn}`)
      raw = raw.slice(1)
      if (raw.length && ["end procedure", "end function"].includes(strip(raw[raw.length - 1]).toLowerCase())) raw = raw.slice(0, -1)
    } else if (first.endsWith(":") && stmtKind(first) !== "control" && strip(partition(first, "(")[0]) === fn) raw = raw.slice(1)
  }
  for (const line of raw) {
    const head = strip(line).toLowerCase()
    if (["algorithm ", "require:", "ensure:", "input:", "output:"].some((p) => head.startsWith(p))) {
      throw new BodyError("algorithm captions and contract headers are generated; store requirements with set, and pass only the procedure body")
    }
    if (head.startsWith("procedure ") || head.startsWith("function ") || head === "end procedure" || head === "end function") {
      throw new BodyError("one procedure per node; represent helper procedures as child nodes")
    }
  }
  const lines = joinContinuations(raw)
  const base = lines.length ? Math.min(...lines.map((ln) => ln.length - lstrip(ln).length)) : 0
  const items: BodyItem[] = []
  for (const ln of lines) {
    const [code, sep, tag] = splitComment(strip(ln))
    const item: BodyItem = { indent: ln.length - lstrip(ln).length - base, code: strip(code) }
    if (sep) {
      let t = strip(tag)
      if (t.includes(" -- ")) {
        const [head, , gl] = partition(t, " -- ")
        t = strip(head)
        if (strip(gl)) item.gloss = strip(gl)
      }
      const words = splitWs(t)
      if (t.startsWith("↗") && words.length > 1) item.reuse = words[1]
      else if (t.startsWith("⇒") || t.startsWith("✓")) item.target = strip(t.slice(1))
      else if (words.length && isNodeId(rstrip(words[0], ":"))) {
        item.child = rstrip(words[0], ":")
        const rest = strip(lstrip(strip(t.slice(words[0].length)), ":"))
        if (rest) item.gloss = rest
      } else item.note = t
    }
    items.push(item)
  }
  return items
}

export const itemTag = (it: BodyItem): string => {
  if (it.child !== undefined) return it.gloss ? `${it.child}: ${it.gloss}` : it.child
  const gloss = it.gloss ? ` -- ${it.gloss}` : ""
  if (it.reuse !== undefined) return `↗ ${it.reuse}${gloss}`
  if (it.target !== undefined) return `⇒ ${it.target}${gloss}`
  return it.note ?? ""
}

export const fmt = (code: string, tag: string, indent: number): string => {
  const left = " ".repeat(indent) + code
  return tag ? `${left}${" ".repeat(Math.max(CODE_COL - left.length, 1))}-- ${tag}` : left
}

export const bodyText = (items: BodyItem[], indent = 2): string[] => items.map((it) => fmt(it.code, itemTag(it), indent + it.indent))

export const bodyHash = (items: BodyItem[]): string => sha1Json(items, { sortKeys: true }).slice(0, 12)

/** Bind approval to all current design content, including dependencies and plans. */
export const proposalHash = (n: NodeRecord): string => fingerprint(n)

export const legacyIntact = (n: NodeRecord): boolean => {
  const fields = ["statement", "gloss", "effect", "contract", "body", "walkthrough", "composition", "decisions", "deferred", "target", "adaptation"]
  const content: Record<string, unknown> = {}
  for (const f of fields) if (truthy(n[f])) content[f] = n[f]
  const digest = sha256Json(content, { sortKeys: true, ensureAscii: false }).slice(0, 16)
  return n.proposal_hash === digest && n.approved_hash === bodyHash(n.body ?? []) && n.contract_hash === contractHash(n)
}

export const intact = (n: NodeRecord): boolean =>
  Boolean(n.approved_content_hash) && n.approved_content_hash === fingerprint(n)
  && n.approved_hash === bodyHash(n.body ?? []) && n.contract_hash === contractHash(n)

export const commaValues = (values: string[]): string[] => {
  const out: string[] = []
  for (const value of values) for (const part of value.split(",")) {
    const p = strip(part)
    if (p && !out.includes(p)) out.push(p)
  }
  return out
}

/** What a caller depends on: the statement and the contract clauses. The body is the node's own business. */
export const contractHash = (n: NodeRecord): string => sha1Json([n.statement ?? "", n.target ?? "", n.contract ?? {}], { sortKeys: true }).slice(0, 12)

export const frontierStatement = (code: string): string => {
  const [lhs, sep, rhs] = partition(code, code.includes("←") ? "←" : "<-")
  if (sep) return `${strip(rhs)} -> ${strip(lhs)}`
  return code.startsWith("->") ? strip(code.slice(2)) : code.toLowerCase().startsWith("return ") ? strip(code.slice(7)) : code
}

export const nodeUnknowns = (n: NodeRecord): string[] => unknowns(n.gloss ?? "", n.effect ?? "", ...Object.values(n.contract ?? {}))

