export const isNodeId = (s: string): boolean => s.length === 5 && s.startsWith("D-") && isDigit(s.slice(2))
export const isCtxId = (s: string): boolean => (s.startsWith("CTX-F") || s.startsWith("CTX-S")) && isDigit(s.slice(5))
export const isAdrId = (s: string): boolean => s.length === 8 && s.startsWith("ADR-") && isDigit(s.slice(4))
export const isIdent = (s: string): boolean => s.length > 0 && isIdentifier(s) && (isAlphaChar(s[0]) || s[0] === "_")

export const anchorOf = (heading: string): string => {
  let keep = ""
  for (const c of heading) keep += isAlnumChar(c) ? c.toLowerCase() : " -_".includes(c) ? " " : ""
  return splitWs(keep).join("-")
}

export const unknowns = (...texts: string[]): string[] => {
  const out = new Set<string>()
  for (const t of texts) {
    for (const w of splitWs(t)) {
      if (w.startsWith("?") && w.length > 1 && isAlphaChar(Array.from(w)[1])) out.add(rstrip(w.slice(1), ",.;:)]}"))
    }
  }
  return sorted(out)
}

export const fnOf = (statement: string): string => {
  const value = signature(statement)
  const [rawName, sep] = partition(value, "(")
  const name = strip(rawName)
  return sep && isIdent(name) ? name : ""
}

const NOT_CALLS = new Set([...CONTROL, "return", "assert", "invariant"])

export const callNames = (code: string): string[] => {
  const out: string[] = []
  const n = code.length
  let i = 0
  while (i < n) {
    const c = code[i]
    if (c === '"' || c === "'") {
      const quote = c
      i += 1
      while (i < n) {
        if (code[i] === "\\") {
          i += 2
          continue
        }
        if (code[i] === quote) {
          i += 1
          break
        }
        i += 1
      }
      continue
    }
    if (isAlphaChar(c) || c === "_") {
      let j = i
      while (j < n && (isAlnumChar(code[j]) || code[j] === "_")) j += 1
      let k = j
      while (k < n && code[k] === " ") k += 1
      const name = code.slice(i, j)
      const prev = i ? code[i - 1] : ""
      if (k < n && code[k] === "(" && prev !== "." && isIdent(name) && !NOT_CALLS.has(name.toLowerCase())) out.push(name)
      i = j
    } else i += 1
  }
  return out
}

export const stmtKind = (code: string): string => {
  const s = strip(code).toLowerCase()
  if (!s) return "comment"
  if (s.startsWith("{") || s.startsWith("assert ") || s.startsWith("invariant ")) return "assert"
  const head = rstrip(split(s, " ", 1)[0], ":")
  if (CONTROL.has(head) && (s.endsWith(":") || s.endsWith(" then") || s.endsWith(" do") || ["else", "repeat", "until", "end"].includes(head))) return "control"
  return "stmt"
}

/** '' when valid, else the reason. */
export const targetOk = (target: string): string => {
  const [head, sep, rest] = partition(target, ": ")
  const headOk = head.length > 0 && Array.from(head).every((c) => isAlnumChar(c) || c === "-" || c === "_") && isLower(head[0])
  if (!sep || !strip(rest) || !head || !headOk) {
    return `Target ${repr(target)} must read '<target>: <identifier>' (dbos: DBOS.startWorkflow, postgres: SELECT ... ORDER BY seq, ts: Promise.all)`
  }
  return ""
}

